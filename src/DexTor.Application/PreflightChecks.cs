internal static class Texts
{
    public static IReadOnlyCollection<string> GetLocalizationKeys(string language)
    {
        var lang = LocaleCatalog.GetSupportedLanguage(language);
        return dictionaries.TryGetValue(lang, out var values)
            ? values.Keys.ToArray()
            : Array.Empty<string>();
    }

    public static string Translate(string language, string key, IReadOnlyDictionary<string, string>? args = null)
    {
        var lang = LocaleCatalog.GetSupportedLanguage(language);
        if (!dictionaries.TryGetValue(lang, out var values))
        {
            values = dictionaries[Localizer.DefaultLanguage];
        }

        if (!values.TryGetValue(key, out var text))
        {
            text = dictionaries[Localizer.DefaultLanguage].TryGetValue(key, out var fallback)
                ? fallback
                : key;
        }

        if (args is null || args.Count == 0)
        {
            return text;
        }

        foreach (var item in args)
        {
            text = text.Replace($"{{{item.Key}}}", item.Value);
        }

        return text;
    }

