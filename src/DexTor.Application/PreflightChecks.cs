public interface ILocalizer
{
    string T(string key, IReadOnlyDictionary<string, string>? args = null);
    bool TryGetLanguage(out string language);
}

public sealed class Localizer : ILocalizer
{
    public string T(string key, IReadOnlyDictionary<string, string>? args = null)
    {
        return Texts.Translate(_language, key, args);
    }

    public bool TryGetLanguage(out string language)
    {
        language = _language;
        return language != DefaultLanguage;
    }

    public static string DefaultLanguage => "en";
    private string _language;

    public Localizer() : this(ResolveLanguage())
    {
    }

    public Localizer(string language)
    {
        _language = LocaleCatalog.GetSupportedLanguage(language);
    }

    public void SetLanguage(string language)
    {
        _language = LocaleCatalog.GetSupportedLanguage(language);
    }

    public static string ResolveLanguage()
    {
        var requested = System.Globalization.CultureInfo.CurrentUICulture.Name;
        return LocaleCatalog.GetSupportedLanguage(requested);
    }
}

public static class LocaleCatalog
{
    public static readonly string[] SupportedLanguages = ["en", "ru", "uk", "de", "es", "fr", "pt-BR", "pl", "tr", "zh-CN"];

    public static string GetSupportedLanguage(string osCulture)
    {
        if (string.IsNullOrWhiteSpace(osCulture))
        {
            return Localizer.DefaultLanguage;
        }

        var candidate = osCulture.Trim().ToLowerInvariant();
        var shortCode = candidate.Split('-').FirstOrDefault();
        if (string.IsNullOrWhiteSpace(shortCode))
        {
            return Localizer.DefaultLanguage;
        }

        return supported.TryGetValue(candidate, out var exact)
            ? exact
            : supported.TryGetValue(shortCode, out var shortMatch)
                ? shortMatch
                : Localizer.DefaultLanguage;
    }

    public static bool HasLanguage(string language)
    {
        return supported.ContainsKey(language.ToLowerInvariant());
    }

    public static IReadOnlyList<string> GetSupportedLanguages()
    {
        return SupportedLanguages;
    }

    public static IReadOnlyCollection<string> GetLocalizationKeys(string language)
    {
        var lang = GetSupportedLanguage(language);
        return Texts.GetLocalizationKeys(lang);
    }

    private static readonly Dictionary<string, string> supported = new Dictionary<string, string>
    {
        ["en"] = "en",
        ["en-us"] = "en",
        ["ru"] = "ru",
        ["ru-ru"] = "ru",
        ["uk"] = "uk",
