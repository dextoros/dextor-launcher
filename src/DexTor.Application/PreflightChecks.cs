namespace DexTor.Application;

public enum PreflightRequirementKind
{
    OperatingSystem,
    ProcessorArchitecture,
    Runtime,
    HostVirtualization,
    LiveImage,
    Memory,
    DiskSpace
}

public enum PreflightRequirementState
{
    Ok,
    Warning,
    Blocker
}

public sealed record PreflightRequirement(
    PreflightRequirementKind Kind,
    PreflightRequirementState State,
    string TitleKey,
    string DescriptionKey,
    IReadOnlyDictionary<string, string>? DescriptionArgs = null,
    string? InfoTextKey = null,
    IReadOnlyDictionary<string, string>? InfoTextArgs = null,
    string? SolutionTextKey = null,
    IReadOnlyDictionary<string, string>? SolutionTextArgs = null,
    string? ActionTextKey = null,
    string? ActionUrl = null);

public sealed record PreflightReport(
    bool CanStart,
    IReadOnlyList<PreflightRequirement> Requirements)
{
    public bool CanContinueWithWarnings => CanStart || Requirements.Count == 0 || Requirements.All(r => r.State != PreflightRequirementState.Blocker);

    public bool RequiresPrepareWhpx =>
        Requirements.Any(r => r.Kind == PreflightRequirementKind.HostVirtualization && r.State == PreflightRequirementState.Warning);

    public bool IsWhpxReady =>
        Requirements.FirstOrDefault(r => r.Kind == PreflightRequirementKind.HostVirtualization)?.State == PreflightRequirementState.Ok;
}

